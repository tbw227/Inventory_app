/**
 * Vercel build prep — put the SPA in same-origin API mode.
 *
 * The browser calls same-origin `/api/v1/*`, and Vercel rewrites `/api/*` to the
 * Railway API. The rewrite lives in the COMMITTED `vercel.json` (Vercel reads it
 * from source before the build, so it must not be generated here). This script
 * only emits the same-origin flag the SPA reads at build time.
 *
 * Railway still needs FRONTEND_URL set (the API refuses to boot without it).
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(__dirname, '..')

function normalizeApiOrigin(raw) {
  let origin = String(raw || '').trim().replace(/\/$/, '')
  if (!origin) return ''
  origin = origin.replace(/^VITE_API_URL=/i, '')
  origin = origin.replace(/\/api\/v1$/i, '').replace(/\/api$/i, '')
  return origin
}

const apiOrigin = normalizeApiOrigin(process.env.VITE_API_URL)
const envLocalPath = path.join(frontendRoot, '.env.production.local')

fs.writeFileSync(
  envLocalPath,
  '# Generated by scripts/vercel-build-setup.mjs - do not commit\nVITE_USE_SAME_ORIGIN_API=true\n'
)

console.info('[vercel-build-setup] SPA will call same-origin /api/v1')
console.info('[vercel-build-setup] /api/* is proxied to Railway via committed vercel.json')
if (apiOrigin) {
  console.info('[vercel-build-setup] Diagnostic origin →', apiOrigin)
}
console.info('[vercel-build-setup] Ensure FRONTEND_URL is set on Railway (API boot requirement)')
