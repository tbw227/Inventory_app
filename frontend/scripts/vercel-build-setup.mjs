/**
 * Vercel build: proxy /api/* to VITE_API_URL and use same-origin /api/v1 in the SPA.
 * Run before `vite build` when deploying the frontend to Vercel.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(__dirname, '..')

function normalizeApiOrigin(raw) {
  let origin = String(raw || '').trim().replace(/\/$/, '')
  if (!origin) return ''
  origin = origin.replace(/\/api\/v1$/i, '').replace(/\/api$/i, '')
  return origin
}

const apiOrigin = normalizeApiOrigin(process.env.VITE_API_URL)
const vercelJsonPath = path.join(frontendRoot, 'vercel.json')
const envLocalPath = path.join(frontendRoot, '.env.production.local')

const spaRewrite = { source: '/((?!api/).*)', destination: '/index.html' }

if (apiOrigin) {
  const rewrites = [
    { source: '/api/:path*', destination: `${apiOrigin}/api/:path*` },
    spaRewrite,
  ]
  fs.writeFileSync(vercelJsonPath, `${JSON.stringify({ rewrites }, null, 2)}\n`)
  fs.writeFileSync(
    envLocalPath,
    '# Generated by scripts/vercel-build-setup.mjs — do not commit\nVITE_USE_SAME_ORIGIN_API=true\n'
  )
  console.info('[vercel-build-setup] API proxy →', `${apiOrigin}/api/*`)
  console.info('[vercel-build-setup] SPA will call same-origin /api/v1')
} else {
  fs.writeFileSync(vercelJsonPath, `${JSON.stringify({ rewrites: [spaRewrite] }, null, 2)}\n`)
  try {
    fs.unlinkSync(envLocalPath)
  } catch {
    /* ignore */
  }
  console.warn(
    '[vercel-build-setup] VITE_API_URL is empty — no /api proxy. Set it in Vercel env vars to your Express API host.'
  )
}
